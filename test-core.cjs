const assert=require('node:assert/strict');
const C=require('./web/core.js');
const p=C.project('RF tests'),f=p.floors[0];
f.aps.push({id:C.id(),name:'AP',x:.1,y:.5,band:'5 GHz',channel:36,power:20,gain:3});
assert.equal(C.validate(JSON.parse(JSON.stringify(p))).name,'RF tests');
const near=C.predict(p,f,.2,.5)[0].dbm,far=C.predict(p,f,.9,.5)[0].dbm;
assert(near>far,'Signal must decay with distance');
const before=C.predict(p,f,.9,.5)[0].dbm;
f.walls.push({id:C.id(),a:{x:.5,y:0},b:{x:.5,y:1},material:'brick',thickness:12});
assert(Math.abs(C.predict(p,f,.9,.5)[0].dbm-before+8)<1e-8,'Wall crossing must apply 8 dB loss');
assert(Math.abs(C.predict(p,f,.2,.5)[0].dbm-near)<1e-8,'Non-crossing path must not lose signal');
const upstairs=C.floor('Floor 2');upstairs.elevation=3;p.floors.push(upstairs);
assert(C.predict(p,upstairs,.1,.5)[0].dbm<C.predict(p,f,.1,.5)[0].dbm,'Floor propagation must attenuate');
const nets=[{ssid:'A',bssid:'a',dbm:-40,band:'5 GHz',channel:36,radio:'802.11ac'},{ssid:'B',bssid:'b',dbm:-60,band:'5 GHz',channel:36,radio:'802.11ax'}];
assert.equal(C.metric(nets,'sir'),20);assert.equal(C.metric(nets,'signal'),-40);assert.equal(C.metric(nets,'secondary'),-60);assert.equal(C.metric(nets,'count'),2);
assert.equal(C.metric([nets[0]],'sir'),null,'No interferer must not fabricate SIR');
assert.equal(C.metric(nets,'signal','missing'),null);
const pt={id:C.id(),x:.5,y:.5,at:new Date().toISOString(),networks:nets,fresh:true};
assert.equal(C.interpolate([pt],f,.5,.5,'signal','all','all',5,-67),-40);
assert.equal(C.interpolate([pt],f,0,0,'signal','all','all',1,-67),null,'Do not fill unsurveyed areas');
assert(C.csv([['=FORMULA','a,"b',-62]]).includes("'=FORMULA"));assert(C.csv([[-62]]).includes('"-62"'),'Numeric RSSI must remain numeric');
for(const bad of [{...p,pathLoss:NaN},{...p,version:99},{...p,floors:[]}])assert.throws(()=>C.validate(bad));
const bad=structuredClone(p);bad.floors[0].image='data:image/svg+xml,<svg/>';assert.throws(()=>C.validate(bad));
for(const t of ['signal','sir','count','band','phy','secondary','low'])assert(!C.color(-65,t).includes('NaN'));
console.log('PASS: project round-trip, input rejection, RF distance/walls/floors, SIR, interpolation bounds, CSV escaping, palette');
